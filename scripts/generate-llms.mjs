/* ────────────────────────────────────────────────────────────────────────────
 * 1. Parse the English guide corpus out of data.ts
 *
 * Strategy: locate the `guides` array, then split it into one chunk per
 * `slug:` line. Everything before that chunk's `body:` template literal is the
 * metadata head, which is plain quoted strings and safe to regex. Field order
 * is not assumed. Bodies are never read.
 * ────────────────────────────────────────────────────────────────────────── */
function readFile(p) {
  if (!fs.existsSync(p)) fail(`expected file not found: ${p}`)
  return fs.readFileSync(p, 'utf8')
}

function parseGuides(src) {
  const start = src.indexOf('export const guides: Guide[] = [')
  if (start === -1) fail('could not find `export const guides` in blog/data.ts')
  const end = src.indexOf('\n];', start)
  if (end === -1) fail('could not find the end of the guides array in blog/data.ts')
  const arr = src.slice(start, end)

  const marks = []
  const slugRe = /^\s*slug:\s*"([^"]+)",/gm
  let m
  while ((m = slugRe.exec(arr)) !== null) marks.push({ at: m.index, slug: m[1] })

  const out = []
  for (let i = 0; i < marks.length; i++) {
    const chunk = arr.slice(marks[i].at, i + 1 < marks.length ? marks[i + 1].at : arr.length)
    const head = chunk.split(/\n\s*body:\s*`/)[0]
    const pick = (field) => {
      const hit = head.match(new RegExp(`${field}:\\s*"([^"]*)"`))
      return hit ? hit[1] : null
    }
    const g = {
      slug: marks[i].slug,
      title: pick('title'),
      description: pick('description'),
      category: pick('category'),
      date: pick('date'),
    }
    for (const k of ['title', 'description', 'category', 'date']) {
      if (!g[k]) fail(`guide "${g.slug}" is missing a parsable ${k}. Refusing to write a partial corpus.`)
    }
    out.push(g)
  }
  return out
}

/**
 * Parse a translation record (dePostTranslations / jaPostTranslations).
 * A localised guide only counts as real when it has a translated `body`, which
 * is the same gate src/app/sitemap.ts applies. Title-and-description-only
 * entries render the English body and are noindexed, so they must not be
 * advertised to AI crawlers either.
 */
function parseTranslations(src, exportName) {
  const start = src.indexOf(`export const ${exportName}`)
  if (start === -1) fail(`could not find \`${exportName}\``)
  const region = src.slice(start)

  const marks = []
  const keyRe = /^ {2}'([a-z0-9-]+)':\s*\{$/gm
  let m
  while ((m = keyRe.exec(region)) !== null) marks.push({ at: m.index, slug: m[1] })

  const map = new Map()
  for (let i = 0; i < marks.length; i++) {
    const chunk = region.slice(marks[i].at, i + 1 < marks.length ? marks[i + 1].at : region.length)
    const head = chunk.split(/\n {4}body:\s*`/)[0]
    const title = head.match(/title:\s*'((?:[^'\\]|\\.)*)'/)
    const desc = head.match(/description:\s*'((?:[^'\\]|\\.)*)'/)
    map.set(marks[i].slug, {
      title: title ? title[1].replace(/\\'/g, "'") : null,
      description: desc ? desc[1].replace(/\\'/g, "'") : null,
      hasBody: /\n {4}body:\s*`/.test(chunk),
    })
  }
  return map
}

/**
 * Pull the authoritative list of retired guide slugs out of next.config.js.
 * Anything with a live 301 must never be listed in an AI surface: it wastes
 * crawl budget and points models at a redirect.
 */
function parseRetiredSlugs(src) {
  const start = src.indexOf('async redirects()')
  if (start === -1) fail('could not find the redirects() block in next.config.js')
  const region = src.slice(start)
  const retired = new Set()

  // The consolidation map: ['old-slug', 'target']
  const tupleRe = /\[\s*'([a-z0-9-]+)',\s*'([a-z0-9/-]+)'\s*\]/g
  let m
  while ((m = tupleRe.exec(region)) !== null) retired.add(m[1])

  // Explicit `source: '/blog/<slug>'` (and /de, /ja mirrors)
  const srcRe = /source:\s*'\/(?:de\/|ja\/)?blog\/([a-z0-9-]+)'/g
  while ((m = srcRe.exec(region)) !== null) retired.add(m[1])

  return retired
}

