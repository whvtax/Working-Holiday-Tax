const isoDate = (d) => d.toISOString().slice(0, 10)

function parseGuideDate(s) {
  const d = new Date(s)
  return Number.isNaN(d.getTime()) ? new Date(LAST_CONTENT_UPDATE) : d
}

const LAST_CONTENT_UPDATE = '2026-08-01'

// DE and JA use a different slug for the Medicare category.
const localCategorySlug = (slug) => (slug === 'medicare-and-other' ? 'medicare' : slug)

function groupByCategory(guides, categoryOrder) {
  const groups = new Map(categoryOrder.map((c) => [c.category, { ...c, guides: [] }]))
  for (const g of guides) {
    if (!groups.has(g.category)) fail(`guide "${g.slug}" has category "${g.category}", which is not in categoryMeta`)
    groups.get(g.category).guides.push(g)
  }
  return [...groups.values()]
}

