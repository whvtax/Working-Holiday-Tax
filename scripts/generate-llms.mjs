/* ────────────────────────────────────────────────────────────────────────────
 * 3. Compliance guard. Runs over every generated byte before it is written.
 * ────────────────────────────────────────────────────────────────────────── */
const FORBIDDEN = [
  [/\$\s?220\b/, 'a price ($220)'],
  [/\$\s?385\b/, 'a price ($385)'],
  [/\bour fee is\b/i, 'a stated fee'],
  [/\bfee of \$\s?\d/i, 'a stated fee'],
  [/\bcosts? \$\s?\d/i, 'a stated fee'],
  [/\bprices? (?:from|at|start)\b/i, 'price framing'],
  [/\bno refund,?\s*no fee\b/i, 'the retired contingent fee model'],
  [/\bno upfront\b/i, 'a "no upfront" claim'],
  [/\bfree check\b/i, 'a "free check" offer'],
  [/(?:deducted?|taken|paid)\s+(?:out\s+)?from\s+your\s+refund/i, 'pay-from-your-refund language'],
  [/\bthree languages\b/i, 'the prohibited "three languages" line'],
  [/public-register/i, 'a link to /public-register, which is a 404'],
  [/tax agent number/i, 'a Tax Agent Number presented as our own credential'],
  [/\bTAN\b/, 'a Tax Agent Number reference'],
  [/registered[^.\n]{0,80}\bas a tax agent\b/i, 'a first person claim to being a registered tax agent'],
  [/\bwe are a registered tax agent\b/i, 'a first person claim to being a registered tax agent'],
  [/\bour registered tax agents?\b/i, 'a first person claim to the registration'],
  [/the the\b/i, 'a botched find and replace ("the the")'],
  [/—/, 'an em dash'],
  [/–/, 'an en dash'],
]

function assertClean(name, text) {
  const lines = text.split('\n')
  const hits = []
  for (const [re, why] of FORBIDDEN) {
    for (let i = 0; i < lines.length; i++) {
      if (re.test(lines[i])) hits.push(`${name}:${i + 1} contains ${why}: ${lines[i].slice(0, 140)}`)
    }
  }
  if (hits.length) fail(`generated output failed the compliance guard.\n  ` + hits.join('\n  '))
}

