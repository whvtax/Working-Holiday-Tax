/**
 * generate-llms.mjs
 *
 * Regenerates the three files that speak directly to AI crawlers:
 *
 *   public/llms.txt          concise site description + guide index
 *   public/llms-full.txt     expanded index with per guide descriptions (EN + DE + JA)
 *   public/sitemap-llms.xml  the live URL list
 *
 * Why this exists: these three files used to be hand maintained while the guide
 * corpus moved under them. They drifted into listing guides that had been
 * removed and 301 redirected, contradicting themselves on counts, and carrying
 * a prohibited credential claim. Generating them from src/app/blog/data.ts
 * means they cannot drift again.
 *
 * Plain Node ESM. No dependencies. The guide data is TypeScript, so it is read
 * with a deliberately narrow regex extraction and then sanity checked hard: if
 * the parse yields an implausible corpus the script throws rather than writing
 * a truncated file over a good one.
 *
 * Run:  node scripts/generate-llms.mjs      (or: npm run generate:llms)
 *
 * ── Compliance rules this file enforces (see plan/00-CORRECTIONS.md) ─────────
 *  1. No price. Ever. Our fee never appears in any AI surface.
 *  2. Never a first person claim to being a registered tax agent. The business
 *     works UNDER THE SUPERVISION OF one. Only the approved sentence is used.
 *  3. The guarantee wording is exact and is never softened or reworded.
 *  4. No em dashes or en dashes anywhere.
 *  5. Never "three languages". We reply in the customer's own language.
 *  6. Nothing is invented: every figure below carries an effective date and a
 *     named source, and every guide line comes from data.ts.
 *
 * Every generated byte is run through assertClean() before it is written.
 */

