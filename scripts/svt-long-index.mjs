#!/usr/bin/env node
// Writes src/lib/svt/content/long/{en,zh,vi}/index.ts from the batch files in
// each folder, so adding a batch never needs a hand-edited import list.
// Run: node scripts/svt-long-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(process.cwd(), 'src/lib/svt/content/long')
for (const lang of ['en', 'zh', 'vi']) {
  const dir = join(root, lang)
  const files = readdirSync(dir).filter(f => f.endsWith('.ts') && f !== 'index.ts').sort()
  const exports = files.map(f => {
    const m = readFileSync(join(dir, f), 'utf8').match(/export const (\w+)\s*:/)
    if (!m) throw new Error(`${lang}/${f}: no exported const`)
    return { file: f.replace(/\.ts$/, ''), name: m[1] }
  })
  const type = lang === 'en' ? 'LongArticle' : 'LongText'
  const shape = lang === 'en' ? `readonly ${type}[]` : `Readonly<Record<string, ${type}>>`
  const merge = lang === 'en'
    ? `[${exports.map(e => `...${e.name}`).join(', ')}]`
    : `{ ${exports.map(e => `...${e.name}`).join(', ')} }`
  writeFileSync(join(dir, 'index.ts'), [
    '// Generated by scripts/svt-long-index.mjs. Do not edit by hand.',
    `import type { ${type} } from '../types'`,
    ...exports.map(e => `import { ${e.name} } from './${e.file}'`),
    '',
    `export const LONG_${lang.toUpperCase()}: ${shape} = ${merge}`,
    '',
  ].join('\n'))
  console.log(`${lang}: ${exports.length} files`)
}
